public class logic_operator
{
    public static void main(String[] args)
    {
        boolean play = true;
        System.out.println(play);

        // True를 False로 반전
        play = !play;
        System.out.println(play);

        // False를 True로 반전
        play = !play;
        System.out.println(play);
    }
}